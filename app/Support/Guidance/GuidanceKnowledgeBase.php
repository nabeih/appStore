    /** @return array<string, array<string, mixed>> */
    public function allowed(User $actor): array
    {
        $topics = array_filter($this->definitions(), function (array $topic) use ($actor): bool {
            $route = Route::getRoutes()->getByName($topic['route']);
            if (! $route || (! empty($topic['owner']) && ! AccessPermissions::canViewOperation($actor))) {
                return false;
            }
            foreach ($topic['permissions'] ?? [] as $permission) {
                if (! $actor->can($permission)) {
                    return false;
                }
            }
            foreach ($route->gatherMiddleware() as $middleware) {
                if (is_string($middleware) && str_starts_with($middleware, 'can:') && ! $actor->can(substr($middleware, 4))) {
                    return false;
                }
            }

            return true;
        });
        if (isset($topics['inventory']) && ! $actor->can('inventory.correct_setup') && ! $actor->can('purchases.manage')) {
            $topics['inventory']['steps'] = ['اختر الفرع وابحث عن المنتج أو الكود لعرض الكميات المتاحة.', 'إضافة البضاعة تحتاج صلاحية مستقلة. اطلب من المسؤول إدخالها من مستندها الصحيح.'];
        }
        if (isset($topics['suppliers']) && ! $actor->can('finance.supplier_pay')) {
            $topics['suppliers']['steps'] = ['ابحث عن المورد وافتح صفحته.', 'راجع الفواتير والمدفوع والمتبقي. تسجيل سداد يحتاج صلاحية مستقلة؛ اطلبه من المسؤول.'];
        }
        if (isset($topics['branches']) && (! $actor->can('branches.create') || ! $actor->can('sales.all_branches'))) {
            $topics['branches']['steps'] = ['افتح الفروع للاطلاع على الفروع المسموحة لك.', 'إنشاء فرع جديد يحتاج صلاحية مستقلة. اطلبه من المالك، ولا تستخدم بيانات فرع آخر بدلًا منه.'];
        }

        return $topics;
    }

    public function link(string $key, User $actor, ?int $branchId = null): ?array
    {
        $topic = $this->allowed($actor)[$key] ?? null;
        if (! $topic) {
            return null;
        }
        $parameters = $topic['parameters'] ?? [];
        if ($branchId !== null) {
            $parameters['branch_id'] = $branchId;
        }

        return ['label' => $topic['title'], 'url' => route($topic['route'], $parameters, false)];
    }

    public function page(?string $routeName): ?string
    {
        if ($routeName && (str_starts_with($routeName, 'sales.returns.') || str_starts_with($routeName, 'sales.exchanges.'))) {
            return 'returns';
        }
        $match = null;
        $length = 0;
        foreach ($this->definitions() as $key => $topic) {
            $prefix = str_replace(['.index', '.show'], '', $topic['route']);
            if ($routeName && ($routeName === $topic['route'] || str_starts_with($routeName, $prefix.'.')) && strlen($prefix) > $length) {
                $match = $key;
                $length = strlen($prefix);
            }
        }

        return $match;
    }
